import re
import string
import secrets

def check_password_strength(password):
    score = 0
    feedback = []
    checks = {
        'length': False,
        'uppercase': False,
        'lowercase': False,
        'number': False,
        'special': False
    }

    # Check minimum length (>= 8)
    if len(password) >= 8:
        score += 1
        checks['length'] = True
    else:
        feedback.append('Use at least 8 characters.')

    # Check uppercase letters (A - Z)
    if re.search(r'[A-Z]', password):
        score += 1
        checks['uppercase'] = True
    else:
        feedback.append('Add an uppercase letter (A - Z).')

    # Check lowercase letters (a - z)
    if re.search(r'[a-z]', password):
        score += 1
        checks['lowercase'] = True
    else:
        feedback.append('Add a lowercase letter (a - z).')

    # Check digits (0 - 9)
    if re.search(r'\d', password):
        score += 1
        checks['number'] = True
    else:
        feedback.append('Add a number (0 - 9).')

    # Check special characters
    if re.search(r'[^A-Za-z0-9]', password):
        score += 1
        checks['special'] = True
    else:
        feedback.append('Add a special character (e.g. !@#$%^&*).')

    levels = {
        0: 'Very Weak',
        1: 'Weak',
        2: 'Moderate',
        3: 'Good',
        4: 'Strong',
        5: 'Very Strong'
    }

    return score, levels[score], feedback, checks


def generate_password(length=16):
    if length < 8:
        length = 8

    groups = [
        string.ascii_uppercase,
        string.ascii_lowercase,
        string.digits,
        '!@#$%^&*()-_=+'
    ]

    # Ensure every character category is included
    password = [secrets.choice(group) for group in groups]
    all_chars = ''.join(groups)

    password.extend(
        secrets.choice(all_chars)
        for _ in range(length - len(password))
    )

    secrets.SystemRandom().shuffle(password)
    return ''.join(password)


if __name__ == '__main__':
    print('=== Password Strengthening System ===')
    password = input('Enter password to evaluate: ')
    score, level, feedback, checks = check_password_strength(password)

    print(f'\nStrength Score: {score}/5')
    print(f'Strength Level: {level}')

    if feedback:
        print('\nSuggestions:')
        for item in feedback:
            print('-', item)
    else:
        print('All password checks passed!')

    choice = input('\nGenerate a strong password? (y/n): ').strip().lower()
    if choice == 'y':
        print('Generated Password:', generate_password())
